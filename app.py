# التبويب الثاني: اختبارات تفاعلية مستوحاة من نظام وايز سكول والوزارة
with tab2:
    st.subheader("📝 بنك الاختبارات والتقييم الذاتي الفوري")
    st.write("اختبر معلوماتك في المناهج الرسمية دون سحب إنترنت من السيرفر المضيف:")
    
    quiz_data = get_wise_quiz()
    for idx, item in enumerate(quiz_data):
        st.markdown(f"**سؤال {idx+1}:** {item['q']}")
        user_ans = st.radio(f"اختر الإجابة الصحيحة للسؤال {idx+1}:", item['opts'], key=f"ans_{idx}")
        
        c_btn1, c_btn2 = st.columns(2)
        with c_btn1:
            if st.button(f"التحقق من إجابة س{idx+1}", key=f"chk_{idx}"):
                if user_ans == item['ans']:
                    st.success("إجابة صحيحة تماماً! بطل ومتميز 🟢")
                else:
                    st.error(f"إجابة خاطئة 🔴 الصواب هو: {item['ans']}")
        with c_btn2:
            if st.button(f"💡 تلميح مساعد لس{idx+1}", key=f"tip_{idx}"):
                st.info(f"مساعدة: {item['tip']}")
        st.markdown("---")

